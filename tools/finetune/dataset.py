def check_no_overlap(extra_test=()):
    """確認三份資料（和 rag_eval 的題目）沒有重複的問法。"""
    train = {q for qs in TRAIN.values() for q in qs}
    val = {q for q, _ in VAL}
    test = {q for q, _ in TEST} | set(extra_test)
    overlap = (train & val) | (train & test) | (val & test)
    assert not overlap, f"問法重複：{overlap}"
    return len(train), len(val), len(test)
